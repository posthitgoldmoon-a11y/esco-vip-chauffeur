import 'package:flutter/material.dart';

class TermsScreen extends StatelessWidget {
  const TermsScreen({super.key});

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: const Text('약관'),
      ),
      body: ListView(
        children: [
          _buildTermTile(
            context,
            '서비스 이용약관',
            () => Navigator.push(
              context,
              MaterialPageRoute(builder: (_) => const ServiceTermsDetailScreen()),
            ),
          ),
          _buildTermTile(
            context,
            '개인정보 처리방침',
            () => Navigator.push(
              context,
              MaterialPageRoute(builder: (_) => const PrivacyPolicyDetailScreen()),
            ),
          ),
          _buildTermTile(
            context,
            '위치기반 서비스 이용약관',
            () => Navigator.push(
              context,
              MaterialPageRoute(builder: (_) => const LocationTermsDetailScreen()),
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildTermTile(BuildContext context, String title, VoidCallback onTap) {
    return Card(
      margin: const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
      child: ListTile(
        title: Text(title),
        trailing: const Icon(Icons.arrow_forward_ios, size: 16),
        onTap: onTap,
      ),
    );
  }
}

